export function interpretarPromedio(promedio) {
  if (promedio === null || promedio === undefined) return 'Sin datos suficientes para evaluacion.';
  if (promedio >= 4.5) return 'Desempeno sobresaliente. Fortaleza consolidada del escenario.';
  if (promedio >= 4.0) return 'Desempeno alto. Cumple ampliamente con las condiciones de calidad.';
  if (promedio >= 3.5) return 'Desempeno satisfactorio. Requiere acciones de mejora puntuales.';
  if (promedio >= 3.0) return 'Desempeno aceptable. Se identifican oportunidades de mejora significativas.';
  if (promedio >= 2.0) return 'Desempeno bajo. Se requieren acciones correctivas prioritarias.';
  return 'Desempeno critico. Intervencion inmediata requerida.';
}

export function nivelAlerta(promedio) {
  if (promedio === null || promedio === undefined) return 'amarillo';
  if (promedio >= 4.0) return 'verde';
  if (promedio >= 3.5) return 'amarillo';
  if (promedio >= 2.5) return 'naranja';
  return 'rojo';
}
